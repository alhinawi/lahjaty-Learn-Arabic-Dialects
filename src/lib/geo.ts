import type { RegionId } from './types'

/** [longitude, latitude] */
export type LonLat = [number, number]

export const MAP_W = 390
export const MAP_H = 172

/** Equirectangular projection fitted to the Arab world. */
export function project([lon, lat]: LonLat): [number, number] {
  return [Math.round((lon + 18) * 4.9 * 10) / 10, Math.round((38.6 - lat) * 5.4 * 10) / 10]
}

export const toPath = (points: LonLat[]) =>
  points.map((p, i) => `${i ? 'L' : 'M'}${project(p).join(' ')}`).join('') + 'Z'

