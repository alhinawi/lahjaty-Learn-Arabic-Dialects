export const messages: Record<Lang, Record<MessageKey, string>> = { ar, en }

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = messages[lang][key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function useT() {
  const lang = useApp((s) => s.lang)
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

/** Picks the Arabic or English field of a named item. */
export function useName() {
  const lang = useApp((s) => s.lang)
  return (item: { name: string; nameEn: string }) => (lang === 'ar' ? item.name : item.nameEn)
}
